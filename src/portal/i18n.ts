export const MESSAGES: Record<Locale, Catalogue> = { en, fr, es, it, de };

/**
 * Maps a BCP 47 tag (`fr`, `fr-CA`, `pt_BR`, `DE`) to a supported locale by
 * its primary subtag, or `undefined` when it names none of them (or is
 * empty), so the caller can keep looking.
 */
export function matchLocale(tag: string | null | undefined): Locale | undefined {
  const primary = (tag ?? "").trim().toLowerCase().split(/[-_]/)[0];
  return SUPPORTED_LOCALES.find((l) => l === primary);
}

/** Whether `key` names a catalogue entry — for keys built from server values (a status, a method). */
export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/** Looks `key` up in `locale`'s catalogue (falling back to `en`) and fills its `{placeholders}`. */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = MESSAGES[locale][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}
