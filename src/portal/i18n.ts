// Alpha Bros enterprise layer — portal string catalogue (locale support).
//
// Every visible string the `<ab-*>` portal elements render lives here, keyed
// once and translated for en, fr, es, it and de. `en` is the source of truth:
// its keys define `MessageKey`, and `test/portal/i18n.test.ts` fails when
// another locale lacks one (or carries a key `en` does not have, or drops a
// `{placeholder}`). A locale outside this list falls back to `en`.
//
// Strings the server sends (a `PortalError`'s own `message`, audit action
// names, organisation role/status values it returns that this file has no
// entry for) are rendered as received: this catalogue only covers the
// portal's own copy.

